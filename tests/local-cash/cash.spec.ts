test("local closing: independently count current funds and preserve snapshot", async ({ page }, info) => {
  const pending = new Set<string>();
  const failures: string[] = [];
  page.on("request", request => { if (request.url().includes("localhost:55441")) pending.add(`${request.method()} ${new URL(request.url()).pathname}`); });
  page.on("requestfinished", request => pending.delete(`${request.method()} ${new URL(request.url()).pathname}`));
  page.on("requestfailed", request => { const label = `${request.method()} ${new URL(request.url()).pathname}`; pending.delete(label); failures.push(`${label}: ${request.failure()?.errorText}`); });
  page.on("pageerror", error => failures.push(error.message));
  page.on("console", message => { if (message.type() === "error" && /CORS|access.control/i.test(message.text())) failures.push(message.text().replace(/token=[^&\s]+/g, "token=<REDACTED>")); });
  page.on("response", response => { if (response.status() >= 400 && response.url().includes("localhost:55441")) failures.push(`${response.status()} ${new URL(response.url()).pathname}`); });
  const headers = { Authorization: `Bearer ${localJwt()}` };
  const current = await page.request.post("http://localhost:55441/rest/v1/rpc/rpc_cash_status", { headers, data: {} });
  expect(current.ok()).toBe(true);
  const status = await current.json();
  const acknowledged = await page.request.post("http://localhost:55441/rest/v1/rpc/rpc_cash_pos_ack", { headers, data: { p_epoch: status.epoch, p_device: "20000000-0000-4000-8000-000000000001", p_device_token: "a".repeat(64), p_version: status.version } });
  expect(acknowledged.ok()).toBe(true);
  await page.goto("/cash");
  await page.getByLabel("ชื่อผู้ใช้", { exact: true }).fill("admin");
  await page.getByLabel("รหัสผ่าน", { exact: true }).fill("fixture-password");
  await page.getByRole("button", { name: "เข้าสู่ระบบ", exact: true }).click();
  await expect(page.getByRole("heading", { name: "เงินสดร้าน", exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath("cash-mobile-local.png"), fullPage: true });
  await page.goto("/close-day");
  try {
    await expect(page.getByTestId("two-fund-closing")).toBeVisible({ timeout: 30000 });
    await expect(page.getByTestId("close-day-error")).toHaveCount(0);
    await page.getByTestId("close-drawer-count").fill(status.drawer);
    await page.getByTestId("close-pending-count").fill(status.available);
    await page.getByTestId("cash-close-review").click();
    await page.getByTestId("cash-close-confirm").click();
    await expect(page.getByTestId("cash-closing-snapshot")).toBeVisible({ timeout: 15000 });
    await expect(page.getByText("ปิดร้านแล้ว แต่ส่ง LINE ไม่สำเร็จ กดส่งสรุปอีกครั้งได้")).toBeVisible();
    await page.screenshot({ path: info.outputPath("closing-mobile-local.png"), fullPage: true });
    console.log(`Local screenshot artifacts: ${info.outputPath("cash-mobile-local.png")} and ${info.outputPath("closing-mobile-local.png")}`);
  } finally {
    await info.attach("local-pending-requests", { body: Buffer.from(JSON.stringify({ pending: [...pending], failures }, null, 2)), contentType: "application/json" });
    console.log("Local closing request diagnostics:", JSON.stringify({ pending: [...pending], failures }));
  }
});

test("local pause: second tab cannot accept offline cash before mobile close", async ({ page: primary, context }, info) => {
  await context.addInitScript(() => {
    localStorage.setItem("ucom-receiving-device-v1", "20000000-0000-4000-8000-000000000001");
    localStorage.setItem("ucom-receiving-token-v1", "a".repeat(64));
  });
  await primary.setViewportSize({ width: 1360, height: 900 });
  await primary.goto("/stock");
  await primary.getByLabel("ชื่อผู้ใช้", { exact: true }).fill("admin");
  await primary.getByLabel("รหัสผ่าน", { exact: true }).fill("fixture-password");
  await primary.getByRole("button", { name: "เข้าสู่ระบบ", exact: true }).click();
  await expect(primary.getByTestId("open-add-product")).toBeVisible();
  await primary.getByTestId("open-add-product").click();
  const name = `LOCAL-PAUSE-${Date.now()}`;
  await primary.getByTestId("add-product-name").fill(name);
  await primary.getByTestId("add-product-price").fill("100");
  await primary.getByTestId("add-product-qty").fill("3");
  await primary.getByTestId("add-product-submit").click();
  await expect(primary.getByRole("dialog")).toBeHidden();
  await primary.goto("/pos");
  const headers = { Authorization: `Bearer ${localJwt()}` };
  const beforeResponse = await primary.request.post("http://localhost:55441/rest/v1/rpc/rpc_cash_status", { headers, data: {} });
  const before = await beforeResponse.json();
  if (before.isReceivingPaused) await primary.getByTestId("cash-pos-resume").click();
  const second = await context.newPage();
  await second.setViewportSize({ width: 1360, height: 900 });
  await second.goto("/pos");
  await second.getByTestId("catalog-search").fill(name);
  await second.locator('[data-testid^="catalog-item-product-"]').click();
  await expect(second.getByTestId("cart-lines")).toHaveAttribute("data-count", "1");
  await primary.getByTestId("cash-pos-pause").click();
  await expect.poll(async () => (await primary.request.post("http://localhost:55441/rest/v1/rpc/rpc_cash_status", { headers, data: {} })).json()).toMatchObject({ isReceivingPaused: true });
  await context.setOffline(true);
  await second.getByTestId("checkout-submit").click();
  await expect(second.getByTestId("checkout-error")).toContainText("ปิดการออกบิล offline");
  expect(await second.evaluate(() => JSON.parse(localStorage.getItem("ucom-pos-queue-v1") ?? "[]").length)).toBe(0);
  await second.screenshot({ path: info.outputPath("paused-second-tab-local.png"), fullPage: true });
  await context.setOffline(false);
  await second.getByTestId("checkout-submit").click();
  await expect(second.getByTestId("checkout-error")).toContainText("หยุดรับเงิน");
  const pausedResponse = await primary.request.post("http://localhost:55441/rest/v1/rpc/rpc_cash_status", { headers, data: {} });
  const paused = await pausedResponse.json();
  expect(paused.drawer).toBe(before.drawer);
  expect(paused.pending).toBe(before.pending);
  expect(paused.ackVersion).toBe(paused.version);
  const mobile = await context.newPage();
  await mobile.setViewportSize({ width: 390, height: 844 });
  await mobile.goto("/close-day");
  await expect(mobile.getByTestId("two-fund-closing")).toBeVisible();
  await expect(mobile.getByTestId("close-day-error")).toHaveCount(0);
  await mobile.getByTestId("close-drawer-count").fill(paused.drawer);
  await mobile.getByTestId("close-pending-count").fill(paused.available);
  await mobile.getByTestId("cash-close-review").click();
  await mobile.getByTestId("cash-close-confirm").click();
  await expect(mobile.getByText("ปิดร้านแล้ว แต่ส่ง LINE ไม่สำเร็จ กดส่งสรุปอีกครั้งได้")).toBeVisible();
  await mobile.screenshot({ path: info.outputPath("paused-mobile-closing-local.png"), fullPage: true });
  await primary.getByTestId("cash-pos-resume").click();
  await expect.poll(async () => (await primary.request.post("http://localhost:55441/rest/v1/rpc/rpc_cash_status", { headers, data: {} })).json()).toMatchObject({ isReceivingPaused: false, ackVersion: null });
  const stalePause = await primary.request.post("http://localhost:55441/rest/v1/rpc/rpc_cash_pos_ack", { headers, data: { p_epoch: paused.epoch, p_device: "20000000-0000-4000-8000-000000000001", p_device_token: "a".repeat(64), p_version: paused.version } });
  expect(stalePause.ok()).toBe(false);
  await expect.poll(async () => (await primary.request.post("http://localhost:55441/rest/v1/rpc/rpc_cash_status", { headers, data: {} })).json()).toMatchObject({ isReceivingPaused: false });
  console.log(`Pause browser artifacts: ${info.outputPath("paused-second-tab-local.png")} and ${info.outputPath("paused-mobile-closing-local.png")}`);
});
